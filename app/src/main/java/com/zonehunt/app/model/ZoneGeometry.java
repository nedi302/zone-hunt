package com.zonehunt.app.model;

import java.util.ArrayList;
import java.util.List;
import java.util.Random;

import com.zonehunt.app.util.Geo;

/**
 * Deterministic path of the shrinking zone.
 *
 * <p>The zone is divided into fixed stages. At the end of a stage the radius
 * has shrunk and the new centre may have moved. The movement of one stage is
 * limited to the radius loss of that stage, so the next circle is always
 * completely inside the current one. By induction every zone also stays
 * inside the initial zone. The movement is driven by a seed shared by all
 * devices, which makes the path identical during the round and in a replay.</p>
 */
public final class ZoneGeometry {

    /** Length of one shrinking stage. */
    public static final long STAGE_MS = 5 * 60_000L;

    public static final class Zone {
        public final double lat;
        public final double lng;
        public final int radiusMeters;

        public Zone(double lat, double lng, int radiusMeters) {
            this.lat = lat;
            this.lng = lng;
            this.radiusMeters = Math.max(0, radiusMeters);
        }
    }

    public static final class Frame {
        public final Zone current;
        public final Zone next;
        public final long elapsedMs;
        public final long nextChangeMs;
        public final boolean lastStage;
        public final int stageIndex;

        private Frame(Zone current, Zone next, long elapsedMs, long nextChangeMs,
                      boolean lastStage, int stageIndex) {
            this.current = current;
            this.next = next;
            this.elapsedMs = elapsedMs;
            this.nextChangeMs = nextChangeMs;
            this.lastStage = lastStage;
            this.stageIndex = stageIndex;
        }

        public long remainingMs() {
            return Math.max(0, nextChangeMs - elapsedMs);
        }
    }

    public final double originLat;
    public final double originLng;
    public final int initialRadiusMeters;
    public final int shrinkMetersPerMinute;
    public final long roundDurationMs;
    public final long seed;
    private final boolean moveCenter;

    private final long[] changeTimesMs;
    private final Zone[] zones;

    /**
     * Stable seed for all devices and replays. The game id is generated by
     * the host and is part of the start snapshot.
     */
    public static long seedFor(String gameId) {
        long hash = 0xcbf29ce484222325L;
        if (gameId != null) {
            for (int i = 0; i < gameId.length(); i++) {
                hash ^= gameId.charAt(i);
                hash *= 0x100000001b3L;
            }
        }
        return hash == Long.MIN_VALUE ? 0L : hash;
    }

    public ZoneGeometry(double originLat, double originLng, int initialRadiusMeters,
                        int shrinkMetersPerMinute, long roundDurationMs, long seed) {
        this(originLat, originLng, initialRadiusMeters, shrinkMetersPerMinute,
                roundDurationMs, seed, true);
    }

    public ZoneGeometry(double originLat, double originLng, int initialRadiusMeters,
                        int shrinkMetersPerMinute, long roundDurationMs, long seed,
                        boolean moveCenter) {
        this.originLat = originLat;
        this.originLng = originLng;
        this.initialRadiusMeters = Math.max(GameSettings.ABSOLUTE_MIN_RADIUS, initialRadiusMeters);
        this.shrinkMetersPerMinute = Math.max(0, shrinkMetersPerMinute);
        this.roundDurationMs = Math.max(0, roundDurationMs);
        this.seed = seed;
        this.moveCenter = moveCenter;

        List<Long> times = new ArrayList<>();
        times.add(0L);
        if (this.roundDurationMs <= 0) {
            times.add(STAGE_MS);
        } else {
            for (long time = STAGE_MS; time < this.roundDurationMs; time += STAGE_MS) {
                times.add(time);
            }
            if (!times.get(times.size() - 1).equals(this.roundDurationMs)) {
                times.add(this.roundDurationMs);
            }
        }
        changeTimesMs = new long[times.size()];
        for (int i = 0; i < changeTimesMs.length; i++) {
            changeTimesMs[i] = times.get(i);
        }
        zones = buildZones();
    }

    /**
     * Returns the current and the next zone for the given hunting time. The
     * hide phase is not part of this value; callers pass zero during it.
     */
    public Frame frameAt(long huntingElapsedMs) {
        long duration = changeTimesMs[changeTimesMs.length - 1];
        long elapsed = Math.max(0, Math.min(duration, huntingElapsedMs));

        int index = changeTimesMs.length - 2;
        for (int i = 0; i < changeTimesMs.length - 1; i++) {
            if (elapsed < changeTimesMs[i + 1]) {
                index = i;
                break;
            }
        }

        long start = changeTimesMs[index];
        long end = changeTimesMs[index + 1];
        double fraction = end <= start ? 1.0
                : (elapsed - start) / (double) (end - start);

        Zone from = zones[index];
        Zone to = zones[index + 1];
        double lat = from.lat + (to.lat - from.lat) * fraction;
        double lng = from.lng + (to.lng - from.lng) * fraction;
        int radius = (int) Math.round(from.radiusMeters
                + (to.radiusMeters - from.radiusMeters) * fraction);
        radius = Math.max(GameSettings.ABSOLUTE_MIN_RADIUS, radius);
        Zone current = new Zone(lat, lng, radius);
        boolean last = index == changeTimesMs.length - 2;
        return new Frame(current, to, elapsed, end, last, index);
    }

    public Zone initialZone() {
        return zones[0];
    }

    public Zone finalZone() {
        return zones[zones.length - 1];
    }

    public int stageCount() {
        return zones.length;
    }

    private Zone[] buildZones() {
        Zone[] result = new Zone[changeTimesMs.length];
        result[0] = new Zone(originLat, originLng, radiusAt(0));

        Random random = new Random(seed);
        double angle = random.nextDouble() * Math.PI * 2.0;
        for (int i = 1; i < result.length; i++) {
            Zone previous = result[i - 1];
            int radius = radiusAt(changeTimesMs[i]);
            double maxStep = Math.max(0, previous.radiusMeters - radius);

            if (i > 1) {
                // Let the direction wander smoothly, but allow turns and
                // reversals so the zone can move back and forth.
                angle += (random.nextDouble() - 0.5) * Math.toRadians(170.0);
            }

            double step = !moveCenter || maxStep <= 0 ? 0
                    : maxStep * (0.70 + random.nextDouble() * 0.30);
            double north = Math.cos(angle) * step;
            double east = Math.sin(angle) * step;
            if (!moveCenter) {
                north = 0;
                east = 0;
            }
            double lat = previous.lat + Geo.latitudeOffset(north);
            double lng = previous.lng + Geo.longitudeOffset(previous.lat, east);

            // Guard against small projection differences at the new latitude.
            double actual = Geo.distanceMeters(previous.lat, previous.lng, lat, lng);
            if (actual > maxStep && actual > 0) {
                double scale = maxStep / actual;
                lat = previous.lat + (lat - previous.lat) * scale;
                lng = previous.lng + (lng - previous.lng) * scale;
            }
            result[i] = new Zone(lat, lng, Math.max(GameSettings.ABSOLUTE_MIN_RADIUS, radius));
        }
        return result;
    }

    private int radiusAt(long huntingElapsedMs) {
        double minutes = Math.max(0, huntingElapsedMs) / 60_000.0;
        int radius = (int) Math.round(initialRadiusMeters - shrinkMetersPerMinute * minutes);
        return Math.max(GameSettings.ABSOLUTE_MIN_RADIUS, radius);
    }
}
